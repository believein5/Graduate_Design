CITE = re.compile(r"\^\[([^\]]+)\]\^")


def parse(s):
    nums = []
    for part in s.split(","):
        a, _, b = part.partition("-")
        nums += range(int(a), int(b or a) + 1)
    return nums


def compress(nums):
    nums, out, i = sorted(set(nums)), [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out += [f"{nums[i]}-{nums[j]}"] if j - i >= 2 else [str(n) for n in nums[i:j + 1]]
        i = j + 1
    return ",".join(out)


