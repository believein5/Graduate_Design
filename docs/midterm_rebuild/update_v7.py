CITE = re.compile(r"\^\[([\d,\-–]+)\]\^|文献\[(\d+)\]")


def expand(s):
    out = []
    for part in s.split(","):
        if re.search(r"[-–]", part):
            x, y = map(int, re.split(r"[-–]", part)); out += list(range(x, y + 1))
        else:
            out.append(int(part))
    return out


def compress(ns):
    ns, out, k = sorted(ns), [], 0
    while k < len(ns):
        j = k
        while j + 1 < len(ns) and ns[j + 1] == ns[j] + 1:
            j += 1
        out.append(str(ns[k]) if j == k else (f"{ns[k]},{ns[j]}" if j == k + 1 else f"{ns[k]}-{ns[j]}")); k = j + 1
    return ",".join(out)


def texts():
    for x in c:
        if x["t"] == "ref":
            continue
        for key in ("text", "note"):
            if isinstance(x.get(key), str):
                yield x, key
        if x["t"] == "table":
            for r in x["rows"]:
                for k in range(len(r)):
                    yield r, k


order = []
for obj, key in texts():
    for m in CITE.finditer(obj[key]):
        for n in expand(m.group(1) or m.group(2)):
            if n not in order:
                order.append(n)
remap = {o: n for n, o in enumerate(order, 1)}


def sub(m):
    if m.group(1):
        return f"^[{compress([remap[n] for n in expand(m.group(1))])}]^"
    return f"文献[{remap[int(m.group(2))]}]"


for obj, key in texts():
    obj[key] = CITE.sub(sub, obj[key])
refs = [x for x in c if x["t"] == "ref"]
start = c.index(refs[0])
byn = {r["n"]: r for r in refs}
print("references:", len(order), "· dropped (old numbers):", [r["n"] for r in refs if r["n"] not in remap])
c[start:] = [{"t": "ref", "n": remap[o], "text": byn[o]["text"]} for o in order]

