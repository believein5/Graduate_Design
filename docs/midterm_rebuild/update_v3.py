def P(t):
    return {"t": "p", "text": t}


def H(level, num, text):
    return {"t": f"h{level}", "num": num, "text": text}


def idx(t, start=None, kind=None):
    hits = [i for i, x in enumerate(c) if (kind is None or x["t"] == kind) and
            (x.get("text", "").startswith(start) if start else False)]
    assert len(hits) == 1, (start, hits)
    return hits[0]


def head(num):
    hits = [i for i, x in enumerate(c) if x["t"] in ("h1", "h2", "h3") and x["num"] == num]
    assert len(hits) == 1, num
    return hits[0]


